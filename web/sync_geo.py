"""Copies the Python engine's location table (engine/geo_data.py) into engine.js.

Run after editing geo_data.py so the page and the Python engine share one table:
    python3 web/sync_geo.py [ENGINE_ROOT]
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = sys.argv[1] if len(sys.argv) > 1 else next(
    p for p in (os.path.dirname(HERE), os.path.dirname(os.path.dirname(HERE))) if os.path.isdir(os.path.join(p, "engine")))
sys.path.insert(0, ROOT)
from engine import geo_data as g  # noqa: E402

data = {
    "CLUBS": {k: list(v) for k, v in g.CLUBS.items()},
    "APPROXIMATE": sorted(g.APPROXIMATE),
    "CITIES": {k: list(v) for k, v in g.CITIES.items()},
    "REGIONS": {k: sorted(v) for k, v in g.REGIONS.items()},
    "STATES": g.STATES,
    "STATE_ABBREVIATIONS": g.STATE_ABBREVIATIONS,
    "SOUTH_BEND": list(g.SOUTH_BEND),
}
START, END = "  // GEO-DATA START (generated by web/sync_geo.py from engine/geo_data.py)\n", "  // GEO-DATA END\n"
path = os.path.join(HERE, "engine.js")
js = open(path, encoding="utf-8").read()
block = START + "  const GEO = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n" + END
if START in js:
    js = js[:js.index(START)] + block + js[js.index(END) + len(END):]
else:
    marker = "  // ================================================================ text.py\n"
    js = js.replace(marker, block + "\n" + marker, 1)
open(path, "w", encoding="utf-8").write(js)
print(f"engine.js: {len(data['CLUBS'])} clubs, {len(data['CITIES'])} cities")
